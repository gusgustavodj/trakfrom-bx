"""Service integration through the explicit Legacy provider contract.

The candidate database is generated by the attested synthetic builder. The
checks follow CONTRACT_LEGACY_PUBLIC_INTEGRATION_V1 and
CONTRACT_V2_TO_SERVICE_LIBRARY_V1, without an inherited test fixture.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from rekordbox_usb.legacy_service_provider import LegacyServiceProvider
from rekordbox_usb.library_provider_registry import LibraryProviderRegistry
from rekordbox_usb.library_service import LibraryExtractionError, extract_library
from rekordbox_usb.models import LibraryDatabase, LibraryKind, UsbSession
from tests.fixtures.synthetic_legacy_pdb import SyntheticLegacyPdbBuilder


def _session(root: Path) -> tuple[UsbSession, Path, bytes]:
    image = (
        SyntheticLegacyPdbBuilder()
        .add_track(11, "Synthetic Track", "Contents/synthetic.wav")
        .add_node(71, "Synthetic List")
        .add_entry(71, 11, 0)
        .build()
    )
    candidate = root / "PIONEER" / "rekordbox" / "export.pdb"
    candidate.parent.mkdir(parents=True)
    candidate.write_bytes(image)
    session = UsbSession(
        session_id="synthetic-session",
        root=str(root),
        libraries=[
            LibraryDatabase(
                kind=LibraryKind.DEVICE_LIBRARY,
                path=str(candidate),
                size_bytes=len(image),
            )
        ],
    )
    return session, candidate, image


def test_explicit_provider_extracts_one_synthetic_library_without_source_writes(
    tmp_path: Path,
) -> None:
    # The public integration contract requires a selected, explicit provider,
    # ordered track/playlist conversion and read-only access to the candidate.
    root = tmp_path / "synthetic-usb"
    session, candidate, image = _session(root)
    data_root = tmp_path / "local-data"
    registry = LibraryProviderRegistry((LegacyServiceProvider(session.session_id, root),))

    library, manifest = extract_library(
        session,
        data_root,
        provider_registry=registry,
        persist_manifest=False,
    )

    assert [track.track_id for track in library.tracks] == [11]
    assert [track.title for track in library.tracks] == ["Synthetic Track"]
    assert [playlist.track_ids for playlist in library.playlists] == [[11]]
    assert candidate.read_bytes() == image
    assert not manifest.exists()


def test_absent_explicit_provider_fails_without_partial_manifest(tmp_path: Path) -> None:
    # The provider contract forbids implicit fallback when no provider resolves.
    root = tmp_path / "synthetic-usb"
    session, candidate, image = _session(root)
    data_root = tmp_path / "local-data"

    with pytest.raises(LibraryExtractionError):
        extract_library(
            session,
            data_root,
            provider_registry=LibraryProviderRegistry(),
            persist_manifest=False,
        )

    assert candidate.read_bytes() == image
    assert not data_root.exists()


def test_provider_read_failure_does_not_publish_partial_library(tmp_path: Path) -> None:
    # A failed reader has no successful service library or local manifest.
    root = tmp_path / "synthetic-usb"
    session, candidate, image = _session(root)
    data_root = tmp_path / "local-data"

    def failing_reader(_root: Path) -> dict:
        return {"status": "READ_ERROR", "error": "synthetic failure", "library": None}

    provider = LegacyServiceProvider(session.session_id, root, reader=failing_reader)
    registry = LibraryProviderRegistry((provider,))

    with pytest.raises(LibraryExtractionError):
        extract_library(
            session,
            data_root,
            provider_registry=registry,
            persist_manifest=False,
        )

    assert candidate.read_bytes() == image
    assert not data_root.exists()
